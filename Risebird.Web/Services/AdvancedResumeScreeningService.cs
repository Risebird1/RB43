    /// <summary>
    /// Advanced (rubric-based) resume screening for IRF candidates, ported from screen.risebird.io.
    ///
    /// One code path for screening a candidate, used by the single-candidate page and the bulk
    /// run alike, so the two cannot disagree on how a resume is read, what the screener is told,
    /// or what is saved. Every outcome carries a reason: the MCQ product returned null on most
    /// failures, which left a blank page indistinguishable from "not yet screened".
    /// </summary>
    public class AdvancedResumeScreeningService
    {
        /// <summary>The criteria generator does not need a whole document, and a very long JD crowds out the rest of the input.</summary>
        private const int MaxJobDescriptionChars = 12000;

        private readonly ICandidateService _candidateService;
        private readonly IAssistantServiceHelper _assistantServiceHelper;
        private readonly IAzureStorageHelper _azureStorageHelper;
        private readonly IPdfReaderHelper _pdfReaderHelper;
        private readonly IApplicationErrorLogger _applicationErrorLogger;

        public AdvancedResumeScreeningService(ICandidateService candidateService, IAssistantServiceHelper assistantServiceHelper,
            IAzureStorageHelper azureStorageHelper, IPdfReaderHelper pdfReaderHelper, IApplicationErrorLogger applicationErrorLogger)
        {
            _candidateService = candidateService;
            _assistantServiceHelper = assistantServiceHelper;
            _azureStorageHelper = azureStorageHelper;
            _pdfReaderHelper = pdfReaderHelper;
            _applicationErrorLogger = applicationErrorLogger;
        }

        public class Outcome
        {
            public bool Success { get; set; }
            public string Error { get; set; }
            public string ResultJson { get; set; }
            public string Verdict { get; set; }
            public int FitmentPercentage { get; set; }
        }

        // ------------------------------------------------------------------- rubric

        /// <summary>
        /// The IRF's saved rubric; when it has none, one is generated from the IRF and saved as
        /// auto-generated, so screening works on every existing IRF without a set-up step. The
        /// rubric screen marks it unreviewed until someone saves it.
        /// </summary>
        public async Task<(ResumeScreeningCriteriaVM Criteria, string Error)> EnsureCriteriaAsync(int irfId, string actor)
        {
            var criteria = await _candidateService.GetIRFResumeScreeningCriteria(irfId);
            if (criteria == null)
            {
                return (null, "This skill channel could not be found.");
            }
            if (criteria.HasCriteria)
            {
                return (criteria, null);
            }

            var (generated, error) = await GenerateCriteriaAsync(criteria);
            if (generated == null)
            {
                return (null, error);
            }

            AdvancedResumeScreening.ClampToColumnWidths(generated);
            if (!await _candidateService.SaveIRFResumeScreeningCriteria(generated, isAutoGenerated: true, savedBy: actor))
            {
                return (null, "A screening rubric was generated but could not be saved.");
            }

            generated.HasCriteria = true;
            generated.IsAutoGenerated = true;
            return (generated, null);
        }

        /// <summary>
        /// Generates a rubric from the IRF without saving it. The inputs are the Risebird
        /// equivalents of what the MCQ product feeds the same prompt: the JD document, the hiring
        /// manager call (latest calibration meeting notes) and the recruiter's own instructions.
        /// </summary>
        public async Task<(ResumeScreeningCriteriaVM Criteria, string Error)> GenerateCriteriaAsync(ResumeScreeningCriteriaVM context)
        {
            try
            {
                var jdText = await ReadJobDescriptionAsync(context);
                if (string.IsNullOrWhiteSpace(jdText))
                {
                    return (null, "This skill channel has no readable job description or JD title to build a screening rubric from.");
                }

                var hiringManagerCall = !string.IsNullOrWhiteSpace(context.CalibrationNotes)
                    ? context.CalibrationNotes
                    : "Not provided. Rely on the recruiter's own description of the role.";

                var response = await _assistantServiceHelper.GenerateJDToScreeningCriteria(
                    hiringManagerCall, jdText, context.RecruiterInstructions);
                var raw = response?.Data?.FirstOrDefault()?.Content?.FirstOrDefault()?.Text?.Value;
                if (string.IsNullOrWhiteSpace(raw))
                {
                    return (null, "The rubric generator did not respond. Check OpenAI:JdToScreeningPromptId and try again.");
                }

                var generated = AdvancedResumeScreening.ParseModelJson<CandidateScreeningInput>(raw);
                if (generated == null)
                {
                    return (null, "The rubric generator returned something that could not be read. Try again.");
                }

                var result = CopyContext(context);
                AdvancedResumeScreening.ApplyGeneratedCriteria(generated, result);

                // The two required criteria. A JD title is always known for an IRF, and the
                // assessment group's skills are a better primary-skills fallback than nothing.
                if (string.IsNullOrWhiteSpace(result.Title))
                {
                    result.Title = context.JDTiltle;
                }
                if (string.IsNullOrWhiteSpace(result.PrimarySkill))
                {
                    result.PrimarySkill = context.AssessmentGroupSkills;
                }
                return (result, null);
            }
            catch (Exception ex)
            {
                await _applicationErrorLogger.LogMessage(LogLevelInfo.Exception, ex);
                return (null, "Something went wrong generating the screening rubric. Try again in a moment.");
            }
        }

        private async Task<string> ReadJobDescriptionAsync(ResumeScreeningCriteriaVM context)
        {
            string text = null;
            if (!string.IsNullOrWhiteSpace(context.JDLink))
            {
                var link = await ToPdfLinkAsync(context.JDLink);
                text = await _pdfReaderHelper.ReadPdfFromUrlAsync(link);
            }

            if (string.IsNullOrWhiteSpace(text))
            {
                // No JD document, or one that could not be read: the title and the assessment
                // group's skills are the job description. A thinner rubric beats none.
                text = string.Join(". ", new[] { context.JDTiltle, context.AssessmentGroupSkills }
                    .Where(x => !string.IsNullOrWhiteSpace(x)));
                return text;
            }

            return text.Length > MaxJobDescriptionChars ? text.Substring(0, MaxJobDescriptionChars) : text;
        }

        private static ResumeScreeningCriteriaVM CopyContext(ResumeScreeningCriteriaVM c)
        {
            return new ResumeScreeningCriteriaVM
            {
                IRFId = c.IRFId,
                IRFName = c.IRFName,
                JDTiltle = c.JDTiltle,
                JDLink = c.JDLink,
                RecruiterInstructions = c.RecruiterInstructions,
                AssessmentGroupSkills = c.AssessmentGroupSkills,
                CalibrationNotes = c.CalibrationNotes,
                HasCriteria = c.HasCriteria,
                IsAutoGenerated = c.IsAutoGenerated,
                CreatedOn = c.CreatedOn,
                CreatedBy = c.CreatedBy,
                UpdatedOn = c.UpdatedOn,
                UpdatedBy = c.UpdatedBy
            };
        }

        // ---------------------------------------------------------------- screening

        public async Task<Outcome> ScreenCandidateAsync(int irfId, int candidateMasterId, string resumeLink, string actor)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(resumeLink))
                {
                    return Fail("No resume on file for this candidate.");
                }

                var (criteria, criteriaError) = await EnsureCriteriaAsync(irfId, actor);
                if (criteria == null)
                {
                    return Fail(criteriaError);
                }

                // Anything that is not a PDF is converted first, because the reader handles PDFs
                // and nothing else - handed a .docx it returns nothing, and that used to surface as
                // an empty page rather than a reason.
                var readableLink = await ToPdfLinkAsync(resumeLink);
                var resumeText = await _pdfReaderHelper.ReadPdfFromUrlAsync(readableLink);
                if (string.IsNullOrWhiteSpace(resumeText))
                {
                    // Named separately so a conversion failure is not reported as a corrupt file:
                    // the two need different remedies.
                    return Fail(IsPdf(resumeLink)
                        ? "Resume text could not be extracted - the file may be scanned or corrupt."
                        : "This resume could not be converted to PDF for reading. Re-upload it as a PDF.");
                }

                var payload = AdvancedResumeScreening.BuildScreeningInput(criteria);
                var response = await _assistantServiceHelper.GenerateAdvancedResumeAnalysis(resumeText, JsonConvert.SerializeObject(payload));
                var raw = AdvancedResumeScreening.StripJsonFence(response?.Data?.FirstOrDefault()?.Content?.FirstOrDefault()?.Text?.Value);
                if (string.IsNullOrWhiteSpace(raw))
                {
                    return Fail("The screening model did not respond. Check OpenAI:AdvancedScreenerPromptId and try again.");
                }

                var analysis = AdvancedResumeScreening.ParseModelJson<AdvancedScreeningResponse>(raw);
                if (analysis == null)
                {
                    return Fail("The screening model returned something that could not be read. Try again.");
                }

                // One fixed vocabulary, whichever scale the model answered on. The original verdict
                // stays in the stored JSON.
                var verdict = AdvancedResumeScreening.NormalizeVerdict(analysis.overallverdict);
                var percentage = AdvancedResumeScreening.ParsePercentage(analysis.overallfitmentpercentage);

                if (!await _candidateService.SaveCandidateAdvancedResumeScreeningResults(irfId, candidateMasterId, raw, verdict, percentage))
                {
                    return new Outcome
                    {
                        Success = false,
                        Error = "Scored, but the result could not be saved.",
                        ResultJson = raw,
                        Verdict = verdict,
                        FitmentPercentage = percentage
                    };
                }

                return new Outcome { Success = true, ResultJson = raw, Verdict = verdict, FitmentPercentage = percentage };
            }
            catch (Exception ex)
            {
                await _applicationErrorLogger.LogMessage(LogLevelInfo.Exception, ex);
                return Fail("Something went wrong screening this resume. Try again in a moment.");
            }
        }

        /// <summary>
        /// Screens every candidate on the IRF with a resume and no advanced screening yet, one at a
        /// time. Sequential on purpose: the rubric is ensured once up front, and a channel's worth
        /// of parallel calls would trip the OpenAI rate limit long before it saved any time.
        /// </summary>
        public async Task ScreenPendingCandidatesAsync(int irfId, string actor, CancellationToken ct)
        {
            var (criteria, criteriaError) = await EnsureCriteriaAsync(irfId, actor);
            if (criteria == null)
            {
                await _applicationErrorLogger.LogMessage(LogLevelInfo.Error,
                    $"Bulk advanced resume screening for IRF {irfId} not started: {criteriaError}", actor);
                return;
            }

            var pending = await _candidateService.GetCandidatesForAdvancedResumeScreening(irfId);
            if (pending == null)
            {
                return;
            }

            int scored = 0, failed = 0;
            foreach (var candidate in pending)
            {
                if (ct.IsCancellationRequested)
                {
                    break;
                }

                var outcome = await ScreenCandidateAsync(irfId, candidate.CandidateMasterId, candidate.ResumeLink, actor);
                if (outcome.Success)
                {
                    scored++;
                }
                else
                {
                    failed++;
                    await _applicationErrorLogger.LogMessage(LogLevelInfo.Warning,
                        $"Bulk advanced resume screening, IRF {irfId}, candidate {candidate.EmailId}: {outcome.Error}", actor);
                }
            }

            await _applicationErrorLogger.LogMessage(LogLevelInfo.Info,
                $"Bulk advanced resume screening for IRF {irfId} finished: {scored} scored, {failed} not scored.", actor);
        }

        // ------------------------------------------------------------------ helpers

        private static bool IsPdf(string url)
        {
            // Case-insensitive, and judged on the path rather than the whole URL so a SAS query
            // string cannot hide the extension. Blob names keep the uploaded file's case, so
            // "Resume.PDF" is an ordinary upload, not an edge case.
            var path = url.Split('?')[0];
            return path.EndsWith(".pdf", StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>A PDF link as-is; anything else converted, falling back to the original link if conversion yields nothing.</summary>
        private async Task<string> ToPdfLinkAsync(string url)
        {
            if (IsPdf(url))
            {
                return url;
            }

            var converted = await _azureStorageHelper.DownloadAndConvertFromDocToPdfAsync(url);
            return string.IsNullOrWhiteSpace(converted) ? url : converted;
        }

        private static Outcome Fail(string error) => new Outcome { Success = false, Error = error };
    }

    /// <summary>
    /// Bulk advanced screening runs here rather than inside the request: a channel can take many
    /// minutes, and the MCQ product's un-awaited call kept using request-scoped services after the
    /// request that owned them had ended.
    /// </summary>
    public sealed class ResumeScreeningBackgroundQueue
    {
        public sealed record BulkScreenIrf(int IrfId, string Actor);

        private readonly Channel<BulkScreenIrf> _channel = Channel.CreateUnbounded<BulkScreenIrf>(new UnboundedChannelOptions { SingleReader = true });

        // IRFs queued or running. A second request for the same IRF while one is in flight is
        // refused: it would pick up the candidates the first run had not reached yet and screen
        // them twice.
        private readonly ConcurrentDictionary<int, byte> _active = new ConcurrentDictionary<int, byte>();

        public bool TryEnqueue(BulkScreenIrf item)
        {
            if (!_active.TryAdd(item.IrfId, 0))
            {
                return false;
            }
            _channel.Writer.TryWrite(item);
            return true;
        }

        public void MarkDone(int irfId) => _active.TryRemove(irfId, out _);

        public ValueTask<BulkScreenIrf> DequeueAsync(CancellationToken ct) => _channel.Reader.ReadAsync(ct);
    }

    public sealed class ResumeScreeningBackgroundWorker : BackgroundService
    {
        private readonly ResumeScreeningBackgroundQueue _queue;
        private readonly IServiceScopeFactory _scopeFactory;

        public ResumeScreeningBackgroundWorker(ResumeScreeningBackgroundQueue queue, IServiceScopeFactory scopeFactory)
        {
            _queue = queue;
            _scopeFactory = scopeFactory;
        }

        protected override async Task ExecuteAsync(CancellationToken stoppingToken)
        {
            while (!stoppingToken.IsCancellationRequested)
            {
                ResumeScreeningBackgroundQueue.BulkScreenIrf item;
                try { item = await _queue.DequeueAsync(stoppingToken); }
                catch (OperationCanceledException) { return; }

                using (var scope = _scopeFactory.CreateScope())
                {
                    var service = scope.ServiceProvider.GetRequiredService<AdvancedResumeScreeningService>();
                    try
                    {
                        await service.ScreenPendingCandidatesAsync(item.IrfId, item.Actor, stoppingToken);
                    }
                    catch (OperationCanceledException) when (stoppingToken.IsCancellationRequested)
                    {
                        return;
                    }
                    catch (Exception ex)
                    {
                        var logger = scope.ServiceProvider.GetService<IApplicationErrorLogger>();
                        if (logger != null)
                        {
                            await logger.LogMessage(LogLevelInfo.Exception, ex);
                        }
                    }
                    finally
                    {
                        _queue.MarkDone(item.IrfId);
                    }
                }
            }
        }
    }
}
