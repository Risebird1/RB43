    public class SectionsInfo
    {
        public bool matched { get; set; }
        public string actualscore { get; set; }
        public string maxscore { get; set; }
        public string reason { get; set; }
        public string observation { get; set; }

        /// <summary>The prompt is not pinned to one key for the explanation; show whichever came back.</summary>
        [JsonIgnore]
        public string reasonOrObservation =>
            !string.IsNullOrWhiteSpace(reason) ? reason :
            !string.IsNullOrWhiteSpace(observation) ? observation :
            null;
    }
