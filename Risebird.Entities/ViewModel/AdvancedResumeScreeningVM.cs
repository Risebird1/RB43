        public string HighestEducationQualification { get; set; }
        public string EducationType { get; set; }
        public string EducationSpecialization { get; set; }
        public string EducationGaps { get; set; }
        public string EducationCertification { get; set; }
        public int TargetEducationInstitutionScore { get; set; }
        public int HighestEducationQualificationScore { get; set; }
        public int EducationTypeScore { get; set; }
        public int EducationSpecializationScore { get; set; }
        public int EducationGapsScore { get; set; }
        public int EducationCertificateScore { get; set; }
    }

    /// <summary>One row of the rubric review screen: a criterion's text and weight, bound by property name.</summary>
    public class ScreeningCriterionRow
    {
        public string Section { get; set; }
        public string Label { get; set; }

        /// <summary>Property name on ResumeScreeningCriteriaVM holding the criterion text.</summary>
        public string TextField { get; set; }

        /// <summary>Property name on ResumeScreeningCriteriaVM holding the weight.</summary>
        public string ScoreField { get; set; }

        public string Text { get; set; }
        public int Score { get; set; }

        /// <summary>JD Title and Primary Skills are required, minimum 1 point.</summary>
        public bool IsRequired { get; set; }

        /// <summary>The IRFResumeScreeningCriteria column width, so the form cannot post text the column would truncate.</summary>
        public int MaxLength { get; set; }
    }

    /// <summary>A candidate the bulk advanced screening run should pick up.</summary>
    public class AdvancedScreeningCandidateRef
    {
        public int IRFId { get; set; }
        public int CandidateMasterId { get; set; }
        public string EmailId { get; set; }
        public string ResumeLink { get; set; }
    }

    // ------------------------------------------------------------------------------------------
    // The payload sent to the advanced screener and returned by the criteria generator.
    //
    // Property names are the JSON contract with the stored OpenAI prompts shared with
    // screen.risebird.io (AIJdToScreeningPromptId writes this shape, AIAdvancedScreenerPromptId
    // reads it). They are deliberately not renamed to C# conventions: Newtonsoft serialises them
    // as written, and a renamed property is a criterion the prompt silently stops seeing.
    // ------------------------------------------------------------------------------------------

    public class CandidateScreeningInput
    {
        public CandidateScreeningInput()
        {
            Skills_Section = new CandidateScreeningSkills();
            Work_Experience = new CandidateScreeningWorkExperience();
            Education = new CandidateScreeningEducation();
        }
        public CandidateScreeningSkills Skills_Section { get; set; }
        public CandidateScreeningWorkExperience Work_Experience { get; set; }
        public CandidateScreeningEducation Education { get; set; }
    }

