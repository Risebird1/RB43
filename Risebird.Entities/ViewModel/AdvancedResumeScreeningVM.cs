    /// IRFResumeScreeningCriteria columns, which match MCQIRF's, so usp_GetIRFResumeScreeningCriteria
    /// maps straight onto this and the review screen can bind by property name.
    /// </summary>
    public class ResumeScreeningCriteriaVM
    {
        // ---- IRF context (read-only on the review screen)
        public int IRFId { get; set; }
        public string IRFName { get; set; }
        public string JDTiltle { get; set; }
        public string JDLink { get; set; }
        public string RecruiterInstructions { get; set; }
        public string AssessmentGroupSkills { get; set; }
        public string CalibrationNotes { get; set; }

        // ---- persistence state
        public bool HasCriteria { get; set; }
        public bool IsAutoGenerated { get; set; }
        public DateTime? CreatedOn { get; set; }
        public string CreatedBy { get; set; }
        public DateTime? UpdatedOn { get; set; }
        public string UpdatedBy { get; set; }

        // ---- Skills
        public string Title { get; set; }
        public string PrimarySkill { get; set; }
        public string SecondarySkill { get; set; }
        public string WorkExperience { get; set; }
        public string SeniorityLevel { get; set; }
        public int JDTitleMaxScore { get; set; }
        public int PrimarySkillsMaxScore { get; set; }
        public int SecondarySkillsMaxScore { get; set; }
        public int WorkExperienceMaxScore { get; set; }
        public int SeniorityLevelScore { get; set; }

        // ---- Work experience
        public string CompanyPercentile { get; set; }
        public string CompanyGenuinity { get; set; }
        public string EmploymentType { get; set; }
        public string VerifiedImpactSkillCredibility { get; set; }
        public string JobFunction { get; set; }
        public string CurrentProjectRelevanceCount { get; set; }
        public string WorkEnvironmentFit { get; set; }
        public string CareerGraphCount { get; set; }
        public string RelevantIndustries { get; set; }
        public string MustHavesCurrentWork { get; set; }
        public string RelevantTools { get; set; }
        public string KPIs { get; set; }
        public string KRAs { get; set; }
        public string Gaps { get; set; }
        public string StabilityIndicators { get; set; }
        public int CompanyPercentileScore { get; set; }
        public int CompanyGenuinityScore { get; set; }
        public int EmploymentTypeScore { get; set; }
        public int VerifiedImpactSkillCredibilityScore { get; set; }
        public int JobFunctionScore { get; set; }
        public int CurrentProjectRelevanceCountScore { get; set; }
        public int WorkEnvironmentFitScore { get; set; }
        public int CareerGraphCountScore { get; set; }
        public int RelevantIndustriesScore { get; set; }
        public int MustHavesCurrentWorkScore { get; set; }
        public int RelevantToolsScore { get; set; }
        public int KPIsScore { get; set; }
        public int KRAsScore { get; set; }
