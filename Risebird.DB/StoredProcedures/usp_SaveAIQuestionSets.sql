-- The second of the two balance gates. ValidateAIQuestionSets in IRFController enforces the same
-- four invariants in C#; this one exists because the procedure must be safe when called by
-- something that is not that controller. If you change one gate, change both. Never delete either.
--
-- I1  every set holds exactly one question per rubric parameter (no repeats, no gaps)
-- I2  no set holds two questions of the same parameter (named separately so the error can name it)
-- I3  each question is used in exactly one set
-- I4  set count equals the smallest per-parameter question pool, never more
--
-- On any violation nothing is written at all: @Success comes back 0 with a user-safe @Message.
Create PROCEDURE [dbo].[usp_SaveAIQuestionSets]
(
    @IRFId int,
    @Items AS [dbo].[AIQuestionSetItems_TableType] READONLY,
    @PromptId varchar(200),
    @PromptVersion varchar(50),
    @CreatedBy varchar(150),
    @Success bit OUTPUT,
    @Message nvarchar(1000) OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;
    SET @Success = 0;
    SET @Message = NULL;

    -- A bare ROLLBACK would discard the caller's transaction as well as ours, so when one is already
    -- open we undo our own work with a savepoint instead. That keeps the procedure safe to call from
    -- inside another transaction, which is also what lets the rejection tests wrap each case in a
    -- transaction they roll back themselves.
    DECLARE @NestedTran bit = CASE WHEN @@TRANCOUNT > 0 THEN 1 ELSE 0 END;

 begin try
  IF @NestedTran = 1 SAVE TRANSACTION SaveAIQSets; ELSE begin tran;

    IF NOT EXISTS (SELECT 1 FROM IRF
                   WHERE id = @IRFId
                     AND ISNULL(IsAIInterview, 0) = 1
                     AND ISNULL(AIInterviewType, 0) = 2)
    BEGIN
        SET @Message = 'This skill channel is not a preset AI interview channel, so question sets cannot be saved for it.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION SaveAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    IF NOT EXISTS (SELECT 1 FROM @Items)
    BEGIN
        SET @Message = 'No question sets were supplied, so nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION SaveAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- Rubric parameters for the channel, and the question pool behind each of them.
    DECLARE @Params TABLE (SkillName nvarchar(500) NOT NULL);
    INSERT INTO @Params (SkillName)
    SELECT DISTINCT LTRIM(RTRIM(tts.SkillName))
    FROM TransTechSkill tts
    WHERE tts.IRFId = @IRFId
      AND tts.SkillName IS NOT NULL
      AND LTRIM(RTRIM(tts.SkillName)) <> '';

    DECLARE @ParamCount int = (SELECT COUNT(*) FROM @Params);

    IF @ParamCount = 0
    BEGIN
        SET @Message = 'This skill channel has no rubric parameters, so question sets cannot be created.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION SaveAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    DECLARE @Pool TABLE (SkillName nvarchar(500) NOT NULL, QuestionCount int NOT NULL);
    INSERT INTO @Pool (SkillName, QuestionCount)
    SELECT p.SkillName,
           (SELECT COUNT(*)
            FROM SkillChannelSampleQuestions q
            WHERE q.IRFId = @IRFId
              AND LTRIM(RTRIM(ISNULL(q.SkillName, ''))) = p.SkillName
              AND q.Comment IS NOT NULL
              AND LTRIM(RTRIM(q.Comment)) <> '')
    FROM @Params p;

    DECLARE @MinPool int = (SELECT MIN(QuestionCount) FROM @Pool);
    DECLARE @SetCount int = (SELECT COUNT(DISTINCT SetName) FROM @Items);

    -- Set names are generated server-side (A..Z, then AA, AB). Anything else means a caller
    -- persisted a value it was given rather than one it derived.
    IF EXISTS (SELECT 1 FROM @Items
               WHERE SetName IS NULL
                  OR LTRIM(RTRIM(SetName)) = ''
                  OR (SetName COLLATE Latin1_General_BIN NOT LIKE '[A-Z]'
                      AND SetName COLLATE Latin1_General_BIN NOT LIKE '[A-Z][A-Z]'))
    BEGIN
        SET @Message = 'Question set names are generated by the server and one of the supplied names is not valid. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION SaveAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- Side check: every question id must exist and belong to this channel.
    IF EXISTS (SELECT 1 FROM @Items i
               WHERE NOT EXISTS (SELECT 1 FROM SkillChannelSampleQuestions q
                                 WHERE q.id = i.QuestionId AND q.IRFId = @IRFId))
    BEGIN
        SET @Message = 'One or more questions do not exist or belong to a different skill channel. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION SaveAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- Side check: the parameter recorded against a question must match the question's own SkillName.
    IF EXISTS (SELECT 1 FROM @Items i
               JOIN SkillChannelSampleQuestions q ON q.id = i.QuestionId AND q.IRFId = @IRFId
               WHERE LTRIM(RTRIM(ISNULL(q.SkillName, ''))) <> LTRIM(RTRIM(ISNULL(i.SkillName, ''))))
    BEGIN
        SET @Message = 'A question was filed under a rubric parameter that is not its own. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION SaveAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- Every parameter used by an item must be a rubric parameter of this channel.
    DECLARE @StraySkill nvarchar(500) = (
        SELECT TOP 1 LTRIM(RTRIM(ISNULL(i.SkillName, '')))
        FROM @Items i
        WHERE NOT EXISTS (SELECT 1 FROM @Params p WHERE p.SkillName = LTRIM(RTRIM(ISNULL(i.SkillName, ''))))
    );
    IF @StraySkill IS NOT NULL
    BEGIN
        SET @Message = 'Rubric parameter "' + @StraySkill + '" is not part of this skill channel''s rubric. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION SaveAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- I3: each question is used in exactly one set. Two papers sharing a question is the leak
    -- this whole feature exists to prevent, so it is checked before anything else structural.
    IF EXISTS (SELECT QuestionId FROM @Items GROUP BY QuestionId HAVING COUNT(*) > 1)
    BEGIN
        SET @Message = 'The same question was placed in more than one set. Each question may be used in exactly one set. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION SaveAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- I2: no set holds two questions of the same parameter.
    DECLARE @DupSet varchar(10), @DupSkill nvarchar(500);
    SELECT TOP 1 @DupSet = SetName, @DupSkill = LTRIM(RTRIM(ISNULL(SkillName, '')))
    FROM @Items
    GROUP BY SetName, LTRIM(RTRIM(ISNULL(SkillName, '')))
    HAVING COUNT(*) > 1;

    IF @DupSet IS NOT NULL
    BEGIN
        SET @Message = 'Set ' + @DupSet + ' holds more than one question for rubric parameter "' + @DupSkill + '". Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION SaveAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- I1: every set holds exactly one question per rubric parameter -- no gaps.
    DECLARE @GapSet varchar(10), @GapSkill nvarchar(500);
    SELECT TOP 1 @GapSet = s.SetName, @GapSkill = p.SkillName
    FROM (SELECT DISTINCT SetName FROM @Items) s
    CROSS JOIN @Params p
    WHERE NOT EXISTS (SELECT 1 FROM @Items i
                      WHERE i.SetName = s.SetName
                        AND LTRIM(RTRIM(ISNULL(i.SkillName, ''))) = p.SkillName)
    ORDER BY s.SetName, p.SkillName;

    IF @GapSet IS NOT NULL
    BEGIN
        SET @Message = 'Set ' + @GapSet + ' has no question for rubric parameter "' + @GapSkill + '". Every set must cover every parameter. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION SaveAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- I4: set count equals the smallest per-parameter pool. One thin parameter caps the channel;
    -- more sets than that would force a question to be reused.
    IF @SetCount <> @MinPool
    BEGIN
        DECLARE @ThinSkill nvarchar(500) = (SELECT TOP 1 SkillName FROM @Pool WHERE QuestionCount = @MinPool ORDER BY SkillName);
        SET @Message = 'This channel supports exactly ' + CAST(@MinPool AS varchar(10))
            + ' set(s) because rubric parameter "' + ISNULL(@ThinSkill, '')
            + '" has only ' + CAST(@MinPool AS varchar(10)) + ' question(s), but '
            + CAST(@SetCount AS varchar(10)) + ' set(s) were supplied. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION SaveAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- An interview is locked to its paper for life, so a set that is already bound cannot be
    -- replaced. Re-dealing the channel would silently change a live candidate's questions.
    IF EXISTS (SELECT 1
               FROM InterviewAIQuestionSet ias
               JOIN AIQuestionSets s ON s.id = ias.SetId
               WHERE s.IRFId = @IRFId)
    BEGIN
        SET @Message = 'Question sets for this channel are already in use by one or more interviews and cannot be re-created. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION SaveAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    DELETE FROM AIQuestionSetItems
    WHERE SetId IN (SELECT id FROM AIQuestionSets WHERE IRFId = @IRFId);

    DELETE FROM AIQuestionSets WHERE IRFId = @IRFId;

    -- TotalMinutes / TotalPoints are summed from the question records the caller read out of this
    -- database, never from anything the model claimed.
    INSERT INTO AIQuestionSets (IRFId, SetName, TotalMinutes, TotalPoints, PromptId, PromptVersion, CreatedBy, CreatedOn)
    SELECT @IRFId,
           i.SetName,
           ISNULL(SUM(ISNULL(i.TotalMinutes, 0)), 0),
           ISNULL(SUM(ISNULL(i.TotalPoints, 0)), 0),
           @PromptId,
           @PromptVersion,
           @CreatedBy,
           GETDATE()
    FROM @Items i
    GROUP BY i.SetName;

    -- Identity order becomes ask order: insert ordered by set, then by the TVP's SortOrder.
    INSERT INTO AIQuestionSetItems (SetId, QuestionId, SkillName)
    SELECT s.id, i.QuestionId, i.SkillName
    FROM @Items i
    JOIN AIQuestionSets s ON s.IRFId = @IRFId AND s.SetName = i.SetName
    ORDER BY s.SetName, i.SortOrder;

    SET @Success = 1;
    SET @Message = 'Created ' + CAST(@SetCount AS varchar(10)) + ' question set(s).';

  IF @NestedTran = 0 commit tran;
 end try
 begin catch
  IF @NestedTran = 1
  BEGIN
   IF XACT_STATE() = 1 ROLLBACK TRANSACTION SaveAIQSets;
  END
  ELSE IF @@TRANCOUNT > 0
   rollback transaction

  DECLARE @ErrMessage varchar(MAX) = ERROR_MESSAGE(),
   @Severity int = ERROR_SEVERITY(),
   @State smallint = ERROR_STATE()

  RAISERROR (@ErrMessage, @Severity, @State)
 end catch
END
GO
