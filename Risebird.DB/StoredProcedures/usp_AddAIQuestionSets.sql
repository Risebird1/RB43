-- "Add more sets": appends question sets to a channel without touching its existing sets or the
-- interviews bound to them (usp_SaveAIQuestionSets refuses to re-create sets once any is in use).
-- The second of the two balance gates; IRFService.AddAIQuestionSets enforces the same rules in C#.
-- If you change one gate, change both. Never delete either.
--
-- The rules are usp_SaveAIQuestionSets', counted over the channel's UNUSED questions only:
-- I1  every new set holds exactly one question per rubric parameter (no repeats, no gaps)
-- I2  no new set holds two questions of the same parameter
-- I3  each question is used in exactly one set, across new AND existing sets
-- I4  new set count equals the smallest per-parameter pool of unused questions
-- plus: new set names are valid and not already taken on the channel. Nothing is ever deleted.
--
-- Eligible questions match usp_GetAIQuestionPoolForSets: a non-empty question, and a code project
-- question only once it has passed validation.
Create PROCEDURE [dbo].[usp_AddAIQuestionSets]
(
    @IRFId int,
    @Items AS [dbo].[AIQuestionSetItems_TableType] READONLY,
    @CreatedBy varchar(150),
    @Success bit OUTPUT,
    @Message nvarchar(1000) OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;
    SET @Success = 0;
    SET @Message = NULL;

    DECLARE @NestedTran bit = CASE WHEN @@TRANCOUNT > 0 THEN 1 ELSE 0 END;

 begin try
  IF @NestedTran = 1 SAVE TRANSACTION AddAIQSets; ELSE begin tran;

    IF NOT EXISTS (SELECT 1 FROM IRF
                   WHERE id = @IRFId
                     AND ISNULL(IsAIInterview, 0) = 1
                     AND ISNULL(AIInterviewType, 0) = 2)
    BEGIN
        SET @Message = 'This skill channel is not a preset AI interview channel, so question sets cannot be saved for it.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    IF NOT EXISTS (SELECT 1 FROM @Items)
    BEGIN
        SET @Message = 'No question sets were supplied, so nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    IF NOT EXISTS (SELECT 1 FROM AIQuestionSets WITH (UPDLOCK, HOLDLOCK) WHERE IRFId = @IRFId)
    BEGIN
        SET @Message = 'This channel has no sets yet. Use Create sets first. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    DECLARE @Params TABLE (SkillName nvarchar(500) NOT NULL);
    INSERT INTO @Params (SkillName)
    SELECT DISTINCT LTRIM(RTRIM(tts.SkillName))
    FROM TransTechSkill tts
    WHERE tts.IRFId = @IRFId
      AND tts.SkillName IS NOT NULL
      AND LTRIM(RTRIM(tts.SkillName)) <> '';

    IF NOT EXISTS (SELECT 1 FROM @Params)
    BEGIN
        SET @Message = 'This skill channel has no rubric parameters, so question sets cannot be created.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- Questions any existing set of the channel already holds.
    DECLARE @Used TABLE (QuestionId int PRIMARY KEY);
    INSERT INTO @Used (QuestionId)
    SELECT DISTINCT i.QuestionId
    FROM AIQuestionSetItems i
    JOIN AIQuestionSets s ON s.id = i.SetId
    WHERE s.IRFId = @IRFId;

    -- Unused eligible questions per parameter.
    DECLARE @Pool TABLE (SkillName nvarchar(500) NOT NULL, QuestionCount int NOT NULL);
    INSERT INTO @Pool (SkillName, QuestionCount)
    SELECT p.SkillName,
           (SELECT COUNT(*)
            FROM SkillChannelSampleQuestions q
            WHERE q.IRFId = @IRFId
              AND LTRIM(RTRIM(ISNULL(q.SkillName, ''))) = p.SkillName
              AND q.Comment IS NOT NULL
              AND LTRIM(RTRIM(q.Comment)) <> ''
              AND (ISNULL(q.IsCodeProjectQuestion, 0) = 0
                   OR EXISTS (SELECT 1 FROM CodeProjectDetails cpd WHERE cpd.QuestionId = q.id AND cpd.ValidationStatus = 'passed'))
              AND NOT EXISTS (SELECT 1 FROM @Used u WHERE u.QuestionId = q.id))
    FROM @Params p;

    DECLARE @MinPool int = (SELECT MIN(QuestionCount) FROM @Pool);
    DECLARE @SetCount int = (SELECT COUNT(DISTINCT SetName) FROM @Items);

    IF EXISTS (SELECT 1 FROM @Items
               WHERE SetName IS NULL
                  OR LTRIM(RTRIM(SetName)) = ''
                  OR (SetName COLLATE Latin1_General_BIN NOT LIKE '[A-Z]'
                      AND SetName COLLATE Latin1_General_BIN NOT LIKE '[A-Z][A-Z]'))
    BEGIN
        SET @Message = 'Question set names are generated by the server and one of the supplied names is not valid. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    DECLARE @TakenName varchar(10) = (SELECT TOP 1 i.SetName FROM @Items i
                                      JOIN AIQuestionSets s ON s.IRFId = @IRFId AND s.SetName = i.SetName);
    IF @TakenName IS NOT NULL
    BEGIN
        SET @Message = 'Set ' + @TakenName + ' already exists on this channel. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    IF EXISTS (SELECT 1 FROM @Items i
               WHERE NOT EXISTS (SELECT 1 FROM SkillChannelSampleQuestions q
                                 WHERE q.id = i.QuestionId AND q.IRFId = @IRFId))
    BEGIN
        SET @Message = 'One or more questions do not exist or belong to a different skill channel. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- A code project question that has not passed validation must never be dealt.
    IF EXISTS (SELECT 1 FROM @Items i
               JOIN SkillChannelSampleQuestions q ON q.id = i.QuestionId
               WHERE ISNULL(q.IsCodeProjectQuestion, 0) = 1
                 AND NOT EXISTS (SELECT 1 FROM CodeProjectDetails cpd WHERE cpd.QuestionId = q.id AND cpd.ValidationStatus = 'passed'))
    BEGIN
        SET @Message = 'A code project question that has not passed validation cannot be put in a set. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    IF EXISTS (SELECT 1 FROM @Items i
               JOIN SkillChannelSampleQuestions q ON q.id = i.QuestionId AND q.IRFId = @IRFId
               WHERE LTRIM(RTRIM(ISNULL(q.SkillName, ''))) <> LTRIM(RTRIM(ISNULL(i.SkillName, ''))))
    BEGIN
        SET @Message = 'A question was filed under a rubric parameter that is not its own. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    DECLARE @StraySkill nvarchar(500) = (
        SELECT TOP 1 LTRIM(RTRIM(ISNULL(i.SkillName, '')))
        FROM @Items i
        WHERE NOT EXISTS (SELECT 1 FROM @Params p WHERE p.SkillName = LTRIM(RTRIM(ISNULL(i.SkillName, ''))))
    );
    IF @StraySkill IS NOT NULL
    BEGIN
        SET @Message = 'Rubric parameter "' + @StraySkill + '" is not part of this skill channel''s rubric. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- I3, across the new sets and against every existing set of the channel.
    IF EXISTS (SELECT QuestionId FROM @Items GROUP BY QuestionId HAVING COUNT(*) > 1)
       OR EXISTS (SELECT 1 FROM @Items i JOIN @Used u ON u.QuestionId = i.QuestionId)
    BEGIN
        SET @Message = 'A question would be used in more than one set. Each question may be used in exactly one set. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- I2
    DECLARE @DupSet varchar(10), @DupSkill nvarchar(500);
    SELECT TOP 1 @DupSet = SetName, @DupSkill = LTRIM(RTRIM(ISNULL(SkillName, '')))
    FROM @Items
    GROUP BY SetName, LTRIM(RTRIM(ISNULL(SkillName, '')))
    HAVING COUNT(*) > 1;
    IF @DupSet IS NOT NULL
    BEGIN
        SET @Message = 'Set ' + @DupSet + ' holds more than one question for rubric parameter "' + @DupSkill + '". Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- I1
    DECLARE @GapSet varchar(10), @GapSkill nvarchar(500);
    SELECT TOP 1 @GapSet = s.SetName, @GapSkill = p.SkillName
    FROM (SELECT DISTINCT SetName FROM @Items) s
    CROSS JOIN @Params p
    WHERE NOT EXISTS (SELECT 1 FROM @Items i
                      WHERE i.SetName = s.SetName
                        AND LTRIM(RTRIM(ISNULL(i.SkillName, ''))) = p.SkillName)
    ORDER BY s.SetName, p.SkillName;
    IF @GapSet IS NOT NULL
    BEGIN
        SET @Message = 'Set ' + @GapSet + ' has no question for rubric parameter "' + @GapSkill + '". Every set must cover every parameter. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    -- I4, over unused questions.
    IF @SetCount <> @MinPool
    BEGIN
        DECLARE @ThinSkill nvarchar(500) = (SELECT TOP 1 SkillName FROM @Pool WHERE QuestionCount = @MinPool ORDER BY SkillName);
        SET @Message = 'This channel can take exactly ' + CAST(@MinPool AS varchar(10))
            + ' more set(s) because rubric parameter "' + ISNULL(@ThinSkill, '')
            + '" has only ' + CAST(@MinPool AS varchar(10)) + ' question(s) not already in a set, but '
            + CAST(@SetCount AS varchar(10)) + ' set(s) were supplied. Nothing was saved.';
        IF @NestedTran = 1 ROLLBACK TRANSACTION AddAIQSets; ELSE ROLLBACK TRANSACTION;
        RETURN;
    END

    INSERT INTO AIQuestionSets (IRFId, SetName, TotalMinutes, TotalPoints, PromptId, PromptVersion, CreatedBy, CreatedOn)
    SELECT @IRFId,
           i.SetName,
           ISNULL(SUM(ISNULL(i.TotalMinutes, 0)), 0),
           ISNULL(SUM(ISNULL(i.TotalPoints, 0)), 0),
           'add-more-sets',
           NULL,
           @CreatedBy,
           GETDATE()
    FROM @Items i
    GROUP BY i.SetName;

    -- Identity order becomes ask order: insert ordered by set, then by the TVP's SortOrder.
    INSERT INTO AIQuestionSetItems (SetId, QuestionId, SkillName)
    SELECT s.id, i.QuestionId, i.SkillName
    FROM @Items i
    JOIN AIQuestionSets s ON s.IRFId = @IRFId AND s.SetName = i.SetName
    ORDER BY s.SetName, i.SortOrder;

    SET @Success = 1;
    SET @Message = 'Added ' + CAST(@SetCount AS varchar(10)) + ' question set(s).';

  IF @NestedTran = 0 commit tran;
 end try
 begin catch
  IF @NestedTran = 1
  BEGIN
   IF XACT_STATE() = 1 ROLLBACK TRANSACTION AddAIQSets;
  END
  ELSE IF @@TRANCOUNT > 0
   rollback transaction

  DECLARE @ErrMessage varchar(MAX) = ERROR_MESSAGE(),
   @Severity int = ERROR_SEVERITY(),
   @State smallint = ERROR_STATE()

  RAISERROR (@ErrMessage, @Severity, @State)
 end catch
END
GO
