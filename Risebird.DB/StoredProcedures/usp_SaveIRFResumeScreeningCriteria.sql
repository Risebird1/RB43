-- Upserts the advanced resume-screening rubric for one IRF. Parameters are declared at the
-- column widths so an over-long value is visible here rather than silently cut at binding.
Create PROCEDURE [dbo].[usp_SaveIRFResumeScreeningCriteria]
@IRFId int,
@IsAutoGenerated bit,
@SavedBy varchar(200),
@Title varchar(300), @PrimarySkill varchar(2000), @SecondarySkill varchar(2000), @WorkExperience varchar(2000), @SeniorityLevel varchar(2000),
@JDTitleMaxScore int, @PrimarySkillsMaxScore int, @SecondarySkillsMaxScore int, @WorkExperienceMaxScore int, @SeniorityLevelScore int,
@CompanyPercentile varchar(2000), @CompanyGenuinity varchar(2000), @EmploymentType varchar(2000), @VerifiedImpactSkillCredibility varchar(2000),
@JobFunction varchar(2000), @CurrentProjectRelevanceCount varchar(2000), @WorkEnvironmentFit varchar(2000), @CareerGraphCount varchar(2000),
@RelevantIndustries varchar(2000), @MustHavesCurrentWork varchar(2000), @RelevantTools varchar(2000), @KPIs varchar(2000), @KRAs varchar(2000),
@Gaps varchar(2000), @StabilityIndicators varchar(2000),
@CompanyPercentileScore int, @CompanyGenuinityScore int, @EmploymentTypeScore int, @VerifiedImpactSkillCredibilityScore int,
@JobFunctionScore int, @CurrentProjectRelevanceCountScore int, @WorkEnvironmentFitScore int, @CareerGraphCountScore int,
@RelevantIndustriesScore int, @MustHavesCurrentWorkScore int, @RelevantToolsScore int, @KPIsScore int, @KRAsScore int,
@GapsScore int, @StabilityIndicatorsScore int,
@TargetEducationInstitution varchar(2000), @HighestEducationQualification varchar(2000), @EducationType varchar(2000),
@EducationSpecialization varchar(2000), @EducationGaps varchar(2000), @EducationCertification varchar(2000),
@TargetEducationInstitutionScore int, @HighestEducationQualificationScore int, @EducationTypeScore int,
@EducationSpecializationScore int, @EducationGapsScore int, @EducationCertificateScore int
AS
Begin
	SET NOCOUNT ON;

	if exists (select 1 from IRFResumeScreeningCriteria where IRFId = @IRFId)
	Begin
		update IRFResumeScreeningCriteria set
		Title = @Title, PrimarySkill = @PrimarySkill, SecondarySkill = @SecondarySkill, WorkExperience = @WorkExperience, SeniorityLevel = @SeniorityLevel,
		JDTitleMaxScore = @JDTitleMaxScore, PrimarySkillsMaxScore = @PrimarySkillsMaxScore, SecondarySkillsMaxScore = @SecondarySkillsMaxScore,
		WorkExperienceMaxScore = @WorkExperienceMaxScore, SeniorityLevelScore = @SeniorityLevelScore,
		CompanyPercentile = @CompanyPercentile, CompanyGenuinity = @CompanyGenuinity, EmploymentType = @EmploymentType,
		VerifiedImpactSkillCredibility = @VerifiedImpactSkillCredibility, JobFunction = @JobFunction,
		CurrentProjectRelevanceCount = @CurrentProjectRelevanceCount, WorkEnvironmentFit = @WorkEnvironmentFit, CareerGraphCount = @CareerGraphCount,
		RelevantIndustries = @RelevantIndustries, MustHavesCurrentWork = @MustHavesCurrentWork, RelevantTools = @RelevantTools,
		KPIs = @KPIs, KRAs = @KRAs, Gaps = @Gaps, StabilityIndicators = @StabilityIndicators,
		CompanyPercentileScore = @CompanyPercentileScore, CompanyGenuinityScore = @CompanyGenuinityScore, EmploymentTypeScore = @EmploymentTypeScore,
		VerifiedImpactSkillCredibilityScore = @VerifiedImpactSkillCredibilityScore, JobFunctionScore = @JobFunctionScore,
		CurrentProjectRelevanceCountScore = @CurrentProjectRelevanceCountScore, WorkEnvironmentFitScore = @WorkEnvironmentFitScore,
		CareerGraphCountScore = @CareerGraphCountScore, RelevantIndustriesScore = @RelevantIndustriesScore,
		MustHavesCurrentWorkScore = @MustHavesCurrentWorkScore, RelevantToolsScore = @RelevantToolsScore, KPIsScore = @KPIsScore,
		KRAsScore = @KRAsScore, GapsScore = @GapsScore, StabilityIndicatorsScore = @StabilityIndicatorsScore,
		TargetEducationInstitution = @TargetEducationInstitution, HighestEducationQualification = @HighestEducationQualification,
		EducationType = @EducationType, EducationSpecialization = @EducationSpecialization, EducationGaps = @EducationGaps,
		EducationCertification = @EducationCertification,
		TargetEducationInstitutionScore = @TargetEducationInstitutionScore, HighestEducationQualificationScore = @HighestEducationQualificationScore,
		EducationTypeScore = @EducationTypeScore, EducationSpecializationScore = @EducationSpecializationScore,
		EducationGapsScore = @EducationGapsScore, EducationCertificateScore = @EducationCertificateScore,
		IsAutoGenerated = @IsAutoGenerated, UpdatedOn = GETUTCDATE(), UpdatedBy = @SavedBy
		where IRFId = @IRFId
	End
	else
	Begin
		insert into IRFResumeScreeningCriteria
		(IRFId, Title, PrimarySkill, SecondarySkill, WorkExperience, SeniorityLevel,
		JDTitleMaxScore, PrimarySkillsMaxScore, SecondarySkillsMaxScore, WorkExperienceMaxScore, SeniorityLevelScore,
		CompanyPercentile, CompanyGenuinity, EmploymentType, VerifiedImpactSkillCredibility, JobFunction,
		CurrentProjectRelevanceCount, WorkEnvironmentFit, CareerGraphCount, RelevantIndustries, MustHavesCurrentWork,
		RelevantTools, KPIs, KRAs, Gaps, StabilityIndicators,
		CompanyPercentileScore, CompanyGenuinityScore, EmploymentTypeScore, VerifiedImpactSkillCredibilityScore, JobFunctionScore,
		CurrentProjectRelevanceCountScore, WorkEnvironmentFitScore, CareerGraphCountScore, RelevantIndustriesScore, MustHavesCurrentWorkScore,
		RelevantToolsScore, KPIsScore, KRAsScore, GapsScore, StabilityIndicatorsScore,
		TargetEducationInstitution, HighestEducationQualification, EducationType, EducationSpecialization, EducationGaps, EducationCertification,
		TargetEducationInstitutionScore, HighestEducationQualificationScore, EducationTypeScore, EducationSpecializationScore,
		EducationGapsScore, EducationCertificateScore,
		IsAutoGenerated, CreatedOn, CreatedBy)
		values
		(@IRFId, @Title, @PrimarySkill, @SecondarySkill, @WorkExperience, @SeniorityLevel,
		@JDTitleMaxScore, @PrimarySkillsMaxScore, @SecondarySkillsMaxScore, @WorkExperienceMaxScore, @SeniorityLevelScore,
		@CompanyPercentile, @CompanyGenuinity, @EmploymentType, @VerifiedImpactSkillCredibility, @JobFunction,
		@CurrentProjectRelevanceCount, @WorkEnvironmentFit, @CareerGraphCount, @RelevantIndustries, @MustHavesCurrentWork,
		@RelevantTools, @KPIs, @KRAs, @Gaps, @StabilityIndicators,
		@CompanyPercentileScore, @CompanyGenuinityScore, @EmploymentTypeScore, @VerifiedImpactSkillCredibilityScore, @JobFunctionScore,
		@CurrentProjectRelevanceCountScore, @WorkEnvironmentFitScore, @CareerGraphCountScore, @RelevantIndustriesScore, @MustHavesCurrentWorkScore,
		@RelevantToolsScore, @KPIsScore, @KRAsScore, @GapsScore, @StabilityIndicatorsScore,
		@TargetEducationInstitution, @HighestEducationQualification, @EducationType, @EducationSpecialization, @EducationGaps, @EducationCertification,
		@TargetEducationInstitutionScore, @HighestEducationQualificationScore, @EducationTypeScore, @EducationSpecializationScore,
		@EducationGapsScore, @EducationCertificateScore,
		@IsAutoGenerated, GETUTCDATE(), @SavedBy)
	End

	select 1 as Saved
End
GO
