-- The advanced resume-screening rubric for one IRF, plus the IRF context the rubric is generated
-- from. Always returns a row for an existing IRF: HasCriteria = 0 means no rubric has been saved
-- yet, and every criterion column is NULL.
--
-- The context columns are the Risebird equivalents of what the MCQ product feeds its criteria
-- generator: the JD document (JDLink), the hiring manager call (latest non-empty calibration
-- meeting notes) and the recruiter's own instructions (VoiceInstructionTranscript).
Create PROCEDURE [dbo].[usp_GetIRFResumeScreeningCriteria]
@IRFId int
AS
Begin
	select irf.id as IRFId, irf.IRFId as IRFName, irf.JDTiltle, irf.JDLink,
	irf.VoiceInstructionTranscript as RecruiterInstructions,
	ag.PrimarySkills as AssessmentGroupSkills,
	cal.Notes as CalibrationNotes,
	case when c.id is null then 0 else 1 end as HasCriteria,
	ISNULL(c.IsAutoGenerated, 0) as IsAutoGenerated, c.CreatedOn, c.CreatedBy, c.UpdatedOn, c.UpdatedBy,
	c.Title, c.PrimarySkill, c.SecondarySkill, c.WorkExperience, c.SeniorityLevel,
	ISNULL(c.JDTitleMaxScore, 0) as JDTitleMaxScore, ISNULL(c.PrimarySkillsMaxScore, 0) as PrimarySkillsMaxScore,
	ISNULL(c.SecondarySkillsMaxScore, 0) as SecondarySkillsMaxScore, ISNULL(c.WorkExperienceMaxScore, 0) as WorkExperienceMaxScore,
	ISNULL(c.SeniorityLevelScore, 0) as SeniorityLevelScore,
	c.CompanyPercentile, c.CompanyGenuinity, c.EmploymentType, c.VerifiedImpactSkillCredibility, c.JobFunction,
	c.CurrentProjectRelevanceCount, c.WorkEnvironmentFit, c.CareerGraphCount, c.RelevantIndustries, c.MustHavesCurrentWork,
	c.RelevantTools, c.KPIs, c.KRAs, c.Gaps, c.StabilityIndicators,
	ISNULL(c.CompanyPercentileScore, 0) as CompanyPercentileScore, ISNULL(c.CompanyGenuinityScore, 0) as CompanyGenuinityScore,
	ISNULL(c.EmploymentTypeScore, 0) as EmploymentTypeScore, ISNULL(c.VerifiedImpactSkillCredibilityScore, 0) as VerifiedImpactSkillCredibilityScore,
	ISNULL(c.JobFunctionScore, 0) as JobFunctionScore, ISNULL(c.CurrentProjectRelevanceCountScore, 0) as CurrentProjectRelevanceCountScore,
	ISNULL(c.WorkEnvironmentFitScore, 0) as WorkEnvironmentFitScore, ISNULL(c.CareerGraphCountScore, 0) as CareerGraphCountScore,
	ISNULL(c.RelevantIndustriesScore, 0) as RelevantIndustriesScore, ISNULL(c.MustHavesCurrentWorkScore, 0) as MustHavesCurrentWorkScore,
	ISNULL(c.RelevantToolsScore, 0) as RelevantToolsScore, ISNULL(c.KPIsScore, 0) as KPIsScore, ISNULL(c.KRAsScore, 0) as KRAsScore,
	ISNULL(c.GapsScore, 0) as GapsScore, ISNULL(c.StabilityIndicatorsScore, 0) as StabilityIndicatorsScore,
	c.TargetEducationInstitution, c.HighestEducationQualification, c.EducationType, c.EducationSpecialization,
	c.EducationGaps, c.EducationCertification,
	ISNULL(c.TargetEducationInstitutionScore, 0) as TargetEducationInstitutionScore,
	ISNULL(c.HighestEducationQualificationScore, 0) as HighestEducationQualificationScore,
	ISNULL(c.EducationTypeScore, 0) as EducationTypeScore, ISNULL(c.EducationSpecializationScore, 0) as EducationSpecializationScore,
	ISNULL(c.EducationGapsScore, 0) as EducationGapsScore, ISNULL(c.EducationCertificateScore, 0) as EducationCertificateScore
	from IRF irf
	left join IRFResumeScreeningCriteria c on c.IRFId = irf.id
	left join AssessmentGroup ag on CAST(ag.id as varchar(100)) = irf.AssessmentGroupId
	outer apply (select top 1 cm.Notes from CalibrationMeetings cm
	             where cm.Irfid = irf.id and ISNULL(LTRIM(RTRIM(cm.Notes)), '') <> ''
	             order by cm.id desc) cal
	where irf.id = @IRFId
End
GO
