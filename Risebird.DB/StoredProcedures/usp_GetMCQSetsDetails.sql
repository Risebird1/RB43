IF EXISTS (SELECT * FROM dbo.sysobjects WHERE id = OBJECT_ID('usp_GetMCQSetsDetails'))
BEGIN
    DROP PROCEDURE dbo.usp_GetMCQSetsDetails
END

SET ANSI_NULLS ON
GO

