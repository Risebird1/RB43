-- The advanced resume-screening rubric for a skill channel (IRF): one row per IRF.
--
-- Ported from screen.risebird.io, where these criteria live as columns on MCQIRF. The column
-- names are kept identical to MCQIRF's so the two products describe a rubric the same way and the
-- same stored OpenAI prompts (AIJdToScreeningPromptId / AIAdvancedScreenerPromptId) read and
-- write it. A separate table rather than more IRF columns because IRF is already very wide and
-- most IRFs will never carry a rubric.
--
-- Each criterion is a text (what the screening model is told it means) and a weight. A weight
-- of zero switches the criterion off: it drops out of the effective maximum rather than counting
-- against the candidate. The weights are advisory against a 300-point budget, not enforced.
IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_NAME = N'IRFResumeScreeningCriteria')
BEGIN

CREATE TABLE [dbo].[IRFResumeScreeningCriteria](
	[id] [int] IDENTITY(1,1) NOT NULL,
	[IRFId] [int] NOT NULL,

	-- Skills
	[Title] [varchar](300) NULL,
	[PrimarySkill] [varchar](2000) NULL,
	[SecondarySkill] [varchar](2000) NULL,
	[WorkExperience] [varchar](2000) NULL,
	[SeniorityLevel] [varchar](2000) NULL,
	[JDTitleMaxScore] [int] NULL,
	[PrimarySkillsMaxScore] [int] NULL,
	[SecondarySkillsMaxScore] [int] NULL,
	[WorkExperienceMaxScore] [int] NULL,
	[SeniorityLevelScore] [int] NULL,

	-- Work experience
	[CompanyPercentile] [varchar](2000) NULL,
	[CompanyGenuinity] [varchar](2000) NULL,
	[EmploymentType] [varchar](2000) NULL,
	[VerifiedImpactSkillCredibility] [varchar](2000) NULL,
	[JobFunction] [varchar](2000) NULL,
	[CurrentProjectRelevanceCount] [varchar](2000) NULL,
	[WorkEnvironmentFit] [varchar](2000) NULL,
	[CareerGraphCount] [varchar](2000) NULL,
	[RelevantIndustries] [varchar](2000) NULL,
	[MustHavesCurrentWork] [varchar](2000) NULL,
	[RelevantTools] [varchar](2000) NULL,
	[KPIs] [varchar](2000) NULL,
	[KRAs] [varchar](2000) NULL,
	[Gaps] [varchar](2000) NULL,
	[StabilityIndicators] [varchar](2000) NULL,
	[CompanyPercentileScore] [int] NULL,
	[CompanyGenuinityScore] [int] NULL,
	[EmploymentTypeScore] [int] NULL,
	[VerifiedImpactSkillCredibilityScore] [int] NULL,
	[JobFunctionScore] [int] NULL,
	[CurrentProjectRelevanceCountScore] [int] NULL,
	[WorkEnvironmentFitScore] [int] NULL,
	[CareerGraphCountScore] [int] NULL,
	[RelevantIndustriesScore] [int] NULL,
	[MustHavesCurrentWorkScore] [int] NULL,
	[RelevantToolsScore] [int] NULL,
	[KPIsScore] [int] NULL,
	[KRAsScore] [int] NULL,
	[GapsScore] [int] NULL,
	[StabilityIndicatorsScore] [int] NULL,

	-- Education
	[TargetEducationInstitution] [varchar](2000) NULL,
	[HighestEducationQualification] [varchar](2000) NULL,
	[EducationType] [varchar](2000) NULL,
	[EducationSpecialization] [varchar](2000) NULL,
	[EducationGaps] [varchar](2000) NULL,
	[EducationCertification] [varchar](2000) NULL,
	[TargetEducationInstitutionScore] [int] NULL,
	[HighestEducationQualificationScore] [int] NULL,
	[EducationTypeScore] [int] NULL,
	[EducationSpecializationScore] [int] NULL,
	[EducationGapsScore] [int] NULL,
	[EducationCertificateScore] [int] NULL,

	-- 1 when the rubric was generated and saved automatically on first screening, 0 once a
	-- person has reviewed and saved it. Shown on the rubric screen so nobody mistakes an
	-- unreviewed rubric for an approved one.
	[IsAutoGenerated] [bit] NOT NULL CONSTRAINT [DF_IRFResumeScreeningCriteria_IsAutoGenerated] DEFAULT (0),
	[CreatedOn] [datetime] NULL,
	[CreatedBy] [varchar](200) NULL,
	[UpdatedOn] [datetime] NULL,
	[UpdatedBy] [varchar](200) NULL,
 CONSTRAINT [PK_IRFResumeScreeningCriteria] PRIMARY KEY CLUSTERED
(
	[id] ASC
)WITH (STATISTICS_NORECOMPUTE = OFF, IGNORE_DUP_KEY = OFF) ON [PRIMARY],
 CONSTRAINT [UQ_IRFResumeScreeningCriteria_IRFId] UNIQUE ([IRFId]),
 CONSTRAINT [FK_IRFResumeScreeningCriteria_IRF] FOREIGN KEY ([IRFId]) REFERENCES [dbo].[IRF] ([id])
) ON [PRIMARY]
END
GO
